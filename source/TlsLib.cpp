/* ==================================================================
 * TlsCertFile implementation – PEMファイル読み込み
 * ================================================================== */

/* DERバイト列蓄積用コールバック */
struct DerAccum {
    unsigned char *buf;
    size_t len;
    size_t cap;
};

static void der_append(void *ctx, const void *src, size_t len)
{
    DerAccum *acc = (DerAccum *)ctx;
    if (acc->len + len > acc->cap) {
        acc->cap = (acc->len + len) * 2;
        if (acc->cap < 1024) acc->cap = 1024;
        acc->buf = (unsigned char *)realloc(acc->buf, acc->cap);
    }
    memcpy(acc->buf + acc->len, src, len);
    acc->len += len;
}

TlsCertFile::TlsCertFile()
    : cert_der_(nullptr), cert_der_len_(0)
    , key_buf_(nullptr), valid_(false)
{
    memset(&rsa_key_, 0, sizeof(rsa_key_));
}

TlsCertFile::~TlsCertFile()
{
    free(cert_der_);
    free(key_buf_);
}

bool TlsCertFile::readFile(const char *path, unsigned char **out, size_t *outLen)
{
    FILE *f = fopen(path, "rb");
    if (!f) return false;

    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (sz <= 0) { fclose(f); return false; }

    *out = (unsigned char *)malloc((size_t)sz);
    if (!*out) { fclose(f); return false; }
    *outLen = fread(*out, 1, (size_t)sz, f);
    fclose(f);
    return (*outLen > 0);
}

bool TlsCertFile::decodePem(const unsigned char *pem, size_t pemLen,
                            const char *objName,
                            unsigned char **derOut, size_t *derLen)
{
    /* BearSSL PEM decoder requires a trailing newline after the end
     * banner to fire BR_PEM_END_OBJ.  Ensure one is present. */
    unsigned char *buf = nullptr;
    if (pemLen > 0 && pem[pemLen - 1] != '\n') {
        buf = (unsigned char *)malloc(pemLen + 1);
        if (!buf) return false;
        memcpy(buf, pem, pemLen);
        buf[pemLen] = '\n';
        pem = buf;
        pemLen += 1;
    }

    br_pem_decoder_context pc;
    br_pem_decoder_init(&pc);

    DerAccum acc = { nullptr, 0, 0 };
    bool found = false;
    bool collecting = false;

    size_t off = 0;
    while (off < pemLen) {
        size_t pushed = br_pem_decoder_push(&pc, pem + off, pemLen - off);
        off += pushed;

        int evt = br_pem_decoder_event(&pc);
        if (evt == BR_PEM_BEGIN_OBJ) {
            const char *name = br_pem_decoder_name(&pc);
            if (strcmp(name, objName) == 0) {
                collecting = true;
                acc.len = 0;
                br_pem_decoder_setdest(&pc, der_append, &acc);
            } else {
                br_pem_decoder_setdest(&pc, nullptr, nullptr);
            }
        } else if (evt == BR_PEM_END_OBJ) {
            if (collecting) {
                found = true;
                break;
            }
        } else if (evt == BR_PEM_ERROR) {
            if (collecting) { free(acc.buf); free(buf); return false; }
        }
        if (pushed == 0 && evt == 0) break; /* avoid infinite loop */
    }

    free(buf);
    if (!found) { free(acc.buf); return false; }
    *derOut = acc.buf;
    *derLen = acc.len;
    return true;
}

bool TlsCertFile::load(const char *certPath, const char *keyPath)
{
    /* 既存データ解放 */
    free(cert_der_); cert_der_ = nullptr; cert_der_len_ = 0;
    free(key_buf_);  key_buf_ = nullptr;
    valid_ = false;

    /* 証明書PEM読み込み */
    unsigned char *certPem = nullptr;
    size_t certPemLen = 0;
    if (!readFile(certPath, &certPem, &certPemLen)) return false;

    if (!decodePem(certPem, certPemLen, "CERTIFICATE", &cert_der_, &cert_der_len_)) {
        free(certPem);
        return false;
    }
    free(certPem);

    /* 秘密鍵PEM読み込み */
    unsigned char *keyPem = nullptr;
    size_t keyPemLen = 0;
    if (!readFile(keyPath, &keyPem, &keyPemLen)) return false;

    /* "RSA PRIVATE KEY" (PKCS#1) または "PRIVATE KEY" (PKCS#8) を試行 */
    unsigned char *keyDer = nullptr;
    size_t keyDerLen = 0;
    if (!decodePem(keyPem, keyPemLen, "RSA PRIVATE KEY", &keyDer, &keyDerLen)) {
        if (!decodePem(keyPem, keyPemLen, "PRIVATE KEY", &keyDer, &keyDerLen)) {
            free(keyPem);
            return false;
        }
    }
    free(keyPem);

    /* BearSSLの秘密鍵デコーダーでRSA鍵をパース */
    br_skey_decoder_context skdc;
    br_skey_decoder_init(&skdc);
    br_skey_decoder_push(&skdc, keyDer, keyDerLen);
    free(keyDer);

    if (br_skey_decoder_last_error(&skdc) != 0) return false;
    if (br_skey_decoder_key_type(&skdc) != BR_KEYTYPE_RSA) return false;

    const br_rsa_private_key *rk = br_skey_decoder_get_rsa(&skdc);
    if (!rk) return false;

    /* RSA鍵の全コンポーネントを単一バッファにコピー
     * (br_skey_decoder_contextのライフタイム後もポインタが有効になるよう) */
    size_t total = rk->plen + rk->qlen + rk->dplen + rk->dqlen + rk->iqlen;
    key_buf_ = (unsigned char *)malloc(total);
    if (!key_buf_) return false;

    unsigned char *p = key_buf_;
    rsa_key_.n_bitlen = rk->n_bitlen;
    memcpy(p, rk->p, rk->plen);  rsa_key_.p = p;  rsa_key_.plen = rk->plen;  p += rk->plen;
    memcpy(p, rk->q, rk->qlen);  rsa_key_.q = p;  rsa_key_.qlen = rk->qlen;  p += rk->qlen;
    memcpy(p, rk->dp, rk->dplen); rsa_key_.dp = p; rsa_key_.dplen = rk->dplen; p += rk->dplen;
    memcpy(p, rk->dq, rk->dqlen); rsa_key_.dq = p; rsa_key_.dqlen = rk->dqlen; p += rk->dqlen;
    memcpy(p, rk->iq, rk->iqlen); rsa_key_.iq = p; rsa_key_.iqlen = rk->iqlen;

    valid_ = true;
    return true;
}

/* ==================================================================
 * Socket I/O callbacks for BearSSL (shared by server and client)
 * ================================================================== */

static int
tls_sockRead(void *ctx, unsigned char *buf, size_t len)
{
    SOCKET fd = *(SOCKET *)ctx;
    if (len > 16384) len = 16384;
    int rlen = recv(fd, (char *)buf, (int)len, 0);
    if (rlen <= 0) return -1;
    return rlen;
}

static int
tls_sockWrite(void *ctx, const unsigned char *buf, size_t len)
{
    SOCKET fd = *(SOCKET *)ctx;
    if (len > 16384) len = 16384;
    int wlen = send(fd, (const char *)buf, (int)len, 0);
    if (wlen <= 0) return -1;
    return wlen;
}

/* ==================================================================
 * x509_noVerify – 証明書検証なしX.509エンジン実装
 * ================================================================== */

static void
xnv_start_chain(const br_x509_class **ctx, const char *server_name)
{
    x509_noVerify_context *xn = (x509_noVerify_context *)ctx;
    (void)server_name;
    xn->first_cert = true;
    xn->key_available = false;
}

static void
xnv_start_cert(const br_x509_class **ctx, uint32_t length)
{
    x509_noVerify_context *xn = (x509_noVerify_context *)ctx;
    (void)length;
    if (xn->first_cert) {
        br_x509_decoder_init(&xn->decoder, nullptr, nullptr);
    }
}

static void
xnv_append(const br_x509_class **ctx, const unsigned char *buf, size_t len)
{
    x509_noVerify_context *xn = (x509_noVerify_context *)ctx;
    if (xn->first_cert) {
        br_x509_decoder_push(&xn->decoder, buf, len);
    }
}

static void
xnv_end_cert(const br_x509_class **ctx)
{
    x509_noVerify_context *xn = (x509_noVerify_context *)ctx;
    if (xn->first_cert) {
        br_x509_pkey *pk = br_x509_decoder_get_pkey(&xn->decoder);
        if (pk) {
            xn->pkey = *pk;
            xn->key_available = true;
        }
        xn->first_cert = false;
    }
}

static unsigned
xnv_end_chain(const br_x509_class **ctx)
{
    (void)ctx;
    return 0;  // 常に成功（検証スキップ）
}

static const br_x509_pkey *
xnv_get_pkey(const br_x509_class *const *ctx, unsigned *usages)
{
    x509_noVerify_context *xn = (x509_noVerify_context *)ctx;
    if (!xn->key_available) return nullptr;
    if (usages) *usages = BR_KEYTYPE_KEYX | BR_KEYTYPE_SIGN;
    return &xn->pkey;
}

const br_x509_class x509_noVerify_vtable = {
    sizeof(x509_noVerify_context),
    xnv_start_chain,
    xnv_start_cert,
    xnv_append,
    xnv_end_cert,
    xnv_end_chain,
    xnv_get_pkey
};

void x509_noVerify_init(x509_noVerify_context *ctx)
{
    ctx->vtable = &x509_noVerify_vtable;
    ctx->first_cert = true;
    ctx->key_available = false;
    memset(&ctx->pkey, 0, sizeof(ctx->pkey));
}

