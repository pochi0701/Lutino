int TlsClientConn::sockWrite(void *ctx, const unsigned char *buf, size_t len) { return tls_sockWrite(ctx, buf, len); }

TlsClientConn::TlsClientConn()
    : sock_(INVALID_SOCKET)
    , active_(false)
{
    memset(&cc_,  0, sizeof(cc_));
    memset(&ioc_, 0, sizeof(ioc_));
}

TlsClientConn::~TlsClientConn()
{
    tlsClose();
}

bool
TlsClientConn::tlsOpen(SOCKET sock, const char *server_name)
{
    if (active_) tlsClose();
    sock_ = sock;

    // no-verify X.509エンジン初期化
    x509_noVerify_init(&xn_);

    // クライアントTLS初期化（全暗号スイート）
    // br_ssl_client_init_fullはxcにアクセスするため一時変数を渡す
    br_x509_minimal_context xc_tmp;
    br_ssl_client_init_full(&cc_, &xc_tmp, nullptr, 0);

    // X.509エンジンをno-verifyに差し替え
    br_ssl_engine_set_x509(&cc_.eng, &xn_.vtable);

    br_ssl_engine_set_buffers_bidi(&cc_.eng,
        iobuf_, BR_SSL_BUFSIZE_INPUT,
        iobuf_ + BR_SSL_BUFSIZE_INPUT, BR_SSL_BUFSIZE_OUTPUT);

    if (!br_ssl_client_reset(&cc_, server_name, 0)) {
        return false;
    }

    br_sslio_init(&ioc_, &cc_.eng,
                  sockRead,  &sock_,
                  sockWrite, &sock_);

    active_ = true;
    return true;
}

int
TlsClientConn::tlsRead(void *buf, size_t len)
{
    if (!active_) return -1;
    return br_sslio_read(&ioc_, buf, len);
}

int
TlsClientConn::tlsWrite(const void *buf, size_t len)
{
    if (!active_) return -1;
    return br_sslio_write_all(&ioc_, buf, len);
}

int
TlsClientConn::tlsFlush()
{
    if (!active_) return -1;
    br_sslio_flush(&ioc_);
    return 0;
}

void
TlsClientConn::tlsClose()
{
    if (!active_) return;
    br_sslio_close(&ioc_);
    if (sock_ != INVALID_SOCKET) {
        closesocket(sock_);
        sock_ = INVALID_SOCKET;
    }
    active_ = false;
}

int
TlsClientConn::lastError() const
{
    return br_ssl_engine_last_error(&cc_.eng);
}

