TlsConn::naEndChain(const br_x509_class **ctx)
{
    x509_noanchor_context *xc = (x509_noanchor_context *)ctx;
    xc->inner.vtable->end_chain(&xc->inner.vtable);
    return 0;
}

const br_x509_pkey *
TlsConn::naGetPkey(const br_x509_class *const *ctx, unsigned *usages)
{
    x509_noanchor_context *xc = (x509_noanchor_context *)(void *)ctx;
    return xc->inner.vtable->get_pkey(&xc->inner.vtable, usages);
}

void
TlsConn::x509NoanchorInit(x509_noanchor_context *xc)
{
    br_x509_minimal_init_full(&xc->inner, NULL, 0);
    xc->vtable = &noanchor_vtable_;
}

TlsConn::TlsConn()
    : mode_(Mode::None)
    , sock_(INVALID_SOCKET)
    , active_(false)
{
    memset(&server_sc_, 0, sizeof(server_sc_));
    memset(&client_sc_, 0, sizeof(client_sc_));
    memset(&client_xc_, 0, sizeof(client_xc_));
    memset(&ioc_, 0, sizeof(ioc_));
    memset(&chain_, 0, sizeof(chain_));
    memset(&sk_, 0, sizeof(sk_));
}

TlsConn::~TlsConn()
{
    close();
}

br_ssl_engine_context*
TlsConn::engine()
{
    switch (mode_) {
    case Mode::Server:
        return &server_sc_.eng;
    case Mode::Client:
        return &client_sc_.eng;
    default:
        return nullptr;
    }
}

bool
TlsConn::open_server(SOCKET sock,
                     const unsigned char *cert, size_t certLen,
                     const br_rsa_private_key *key)
{
    if (active_) close();
    sock_ = sock;
    mode_ = Mode::Server;
    chain_.data = const_cast<unsigned char *>(cert);
    chain_.data_len = certLen;
    sk_ = *key;
    br_ssl_server_init_full_rsa(&server_sc_, &chain_, 1, &sk_);
    br_ssl_engine_set_buffers_bidi(&server_sc_.eng,
        iobuf_, BR_SSL_BUFSIZE_INPUT,
        iobuf_ + BR_SSL_BUFSIZE_INPUT, BR_SSL_BUFSIZE_OUTPUT);
    br_ssl_server_reset(&server_sc_);
    br_sslio_init(&ioc_, &server_sc_.eng, sockRead, &sock_, sockWrite, &sock_);
    active_ = true;
    return true;
}

bool
TlsConn::open_client(SOCKET sock, const char* server_name)
{
    if (active_) close();
    sock_ = sock;
    mode_ = Mode::Client;
    server_name_ = server_name != nullptr ? server_name : "";
    x509NoanchorInit(&client_xc_);
    br_x509_minimal_context dummy_xc;
    memset(&dummy_xc, 0, sizeof(dummy_xc));
    br_ssl_client_init_full(&client_sc_, &dummy_xc, NULL, 0);
    br_ssl_engine_set_x509(&client_sc_.eng, &client_xc_.vtable);
    br_ssl_engine_set_buffers_bidi(&client_sc_.eng,
        iobuf_, BR_SSL_BUFSIZE_INPUT,
        iobuf_ + BR_SSL_BUFSIZE_INPUT, BR_SSL_BUFSIZE_OUTPUT);
    if (!br_ssl_client_reset(&client_sc_, server_name_.c_str(), 0)) {
        mode_ = Mode::None;
        sock_ = INVALID_SOCKET;
        return false;
    }
    br_sslio_init(&ioc_, &client_sc_.eng, sockRead, &sock_, sockWrite, &sock_);
    active_ = true;
    return true;
}

int
TlsConn::read(void *buf, size_t len)
{
    if (!active_) return -1;
    return br_sslio_read(&ioc_, buf, len);
}

int
TlsConn::write(const void *buf, size_t len)
{
    if (!active_) return -1;
    return br_sslio_write_all(&ioc_, buf, len);
}

int
TlsConn::flush()
{
    if (!active_) return -1;
    br_sslio_flush(&ioc_);
    return 0;
}

void
TlsConn::close()
{
    if (!active_) return;
    br_sslio_close(&ioc_);
    if (sock_ != INVALID_SOCKET) {
#ifdef __linux__
        ::close(sock_);
#else
        closesocket(sock_);
#endif
        sock_ = INVALID_SOCKET;
    }
    mode_ = Mode::None;
    active_ = false;
    server_name_.clear();
}

bool
ltn_tls_attach(SOCKET socket)
{
    auto conn = std::make_shared<TlsConn>();
    if (!conn->open_server(socket, TEST_CERT, sizeof(TEST_CERT), &TEST_KEY)) {
        return false;
    }
    std::lock_guard<std::mutex> lock(g_tls_mutex);
    g_tls_connections[socket] = conn;
    return true;
}

bool
ltn_tls_attach_client(SOCKET socket, const char* server_name)
{
    auto conn = std::make_shared<TlsConn>();
    if (!conn->open_client(socket, server_name)) {
        return false;
    }
    std::lock_guard<std::mutex> lock(g_tls_mutex);
    g_tls_connections[socket] = conn;
    return true;
}

bool
ltn_tls_active(SOCKET socket)
{
    std::lock_guard<std::mutex> lock(g_tls_mutex);
    return g_tls_connections.find(socket) != g_tls_connections.end();
}

int
ltn_tls_send(SOCKET socket, const char* buffer, size_t length)
{
    auto conn = find_connection(socket);
    if (!conn) {
        return -1;
    }
    if (conn->write(buffer, length) != 0) {
        return -1;
    }
    if (conn->flush() != 0) {
        return -1;
    }
    return static_cast<int>(length);
}

int
ltn_tls_recv(SOCKET socket, char* buffer, size_t length)
{
    auto conn = find_connection(socket);
    if (!conn) {
        return -1;
    }
    return conn->read(buffer, length);
}

int
ltn_tls_close(SOCKET socket)
{
    std::shared_ptr<TlsConn> conn;
    {
        std::lock_guard<std::mutex> lock(g_tls_mutex);
        auto it = g_tls_connections.find(socket);
        if (it == g_tls_connections.end()) {
            return -1;
        }
        conn = it->second;
        g_tls_connections.erase(it);
    }
    conn->close();
    return 0;
}

void
ltn_tls_shutdown_all(void)
{
    std::unordered_map<SOCKET, std::shared_ptr<TlsConn>> connections;
    {
        std::lock_guard<std::mutex> lock(g_tls_mutex);
        connections.swap(g_tls_connections);
    }
    for (const auto& entry : connections) {
        entry.second->close();
    }
}
